/**
 * Resolve a Lucide icon component from a string name.
 * Service/CMS data stores icon names as strings (e.g. "Globe").
 */
export function resolveIcon(name) {
  if (!name || typeof name !== "string") {
    return DEFAULT_ICON;
  }

  return iconMap[name] || DEFAULT_ICON;
}

